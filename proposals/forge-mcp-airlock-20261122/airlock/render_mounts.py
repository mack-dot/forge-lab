# render_mounts.py - turn forge.yaml readonly_paths of the form "<dir>/**" into a compose
# override that mounts those workspace subdirectories READ-ONLY in the agent container
# (Docker volume subpath mounts). Other glob forms are enforced by file ownership and
# mode only (see workspace.apply_permissions) and in MCP tools. NATIVE CHECK.
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from policy import Policy  # noqa: E402

pol = Policy.load(sys.argv[1])
service = sys.argv[2] if len(sys.argv) > 2 else "agent"
mounts = []
for pat in pol.readonly.patterns:
    m = re.fullmatch(r"([A-Za-z0-9._-]+(?:/[A-Za-z0-9._-]+)*)/\*\*", pat)
    if m and ".." not in m.group(1).split("/"):
        mounts.append(m.group(1))
print("# generated by airlock/render_mounts.py from forge.yaml; do not edit")
print("services:")
print(f"  {service}:")
print("    volumes:")
if not mounts:
    print("      []")
for d in mounts:
    print("      - type: volume")
    print("        source: ws")
    print(f"        target: {pol.agent_root.rstrip('/')}/{d}")
    print("        read_only: true")
    print("        volume:")
    print(f"          subpath: {d}")
